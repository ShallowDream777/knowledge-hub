# 同名栏目在不同主题中有不同含义，按文件限定，不能全局替换。
SCOPED = {
    '英语语法知识字典/07 情态动词/情态动词.md': {'时态分类': '情态动词基础'},
}
NUMBERING = re.compile(r'^(?P<prefix>(?:\d+(?:\.\d+)*[ .、]+|[一二三四五六七八九十百]+、))(?P<title>.+)$')


def rename_title(title, path=None):
    if path is not None:
        try:
            key = str(Path(path).resolve().relative_to(VAULT)).replace('\\', '/')
        except ValueError:
            key = ''
        if title in SCOPED.get(key, {}):
            return SCOPED[key][title]
    if title in TITLES:
        return TITLES[title]
    match = NUMBERING.match(title)
    if match and match['title'] in TITLES:
        return match['prefix'] + TITLES[match['title']]
    if title.startswith('就地练习：'):
        return '练习：' + title.removeprefix('就地练习：')
    return title


def rename_text(text, path=None):
    """只改标题及链接中的标题文字；不对知识段落进行字符串替换。"""
    text = re.sub(r'^(#{1,6} )([^\r\n]+)', lambda m: m[1]+rename_title(m[2], path), text, flags=re.M)

    def wiki(match):
        target, sep, label = match[1].partition('|')
        file, fragment, heading = target.partition('#')
        if fragment:
            target = file + '#' + rename_title(heading, path)
        if sep:
            label = rename_title(label, path)
        return '[[' + target + (sep+label if sep else '') + ']]'

    def markdown(match):
        label, href = match[1], match[2]
        bracketed = href.startswith('<') and href.endswith('>')
        url = href[1:-1] if bracketed else href
        if re.match(r'(?:[a-z][a-z0-9+.-]*:|//)',url,re.I):
            return match[0]
        file, sep, fragment = url.partition('#')
        if sep:
            target_path = (Path(path).parent/unquote(file)).resolve() if path and file else path
            label = rename_title(label, target_path)
            renamed = rename_title(unquote(fragment), target_path)
            if renamed != unquote(fragment):
                url = file+'#'+quote(renamed, safe='')
                if label == unquote(fragment):
                    label = renamed
        return '['+rename_title(label, path)+']('+('<'+url+'>' if bracketed else url)+')'

    text = re.sub(r'\[\[([^\]\r\n]+)\]\]', wiki, text)
    return re.sub(r'\[([^\]\r\n]+)\]\((<[^>\r\n]+>|[^)\r\n]+)\)', markdown, text)


def legacy_source(text, path):
    """原资料仅改标题；切分课程仍沿用既有来源名称，确保编排规则稳定。"""
    record=Path(__file__).with_name('标题调整明细.json')
    if not record.exists():
        return text
    key=str(Path(path).resolve().relative_to(VAULT)).replace('\\','/')
    entry=next((row for row in json.loads(record.read_text(encoding='utf-8'))['修改文件'] if row['文件']==key),None)
    if not entry:
        return text
    reverse={row['新标题']:row['原标题'] for row in entry['标题']}
    def restore(match):
        return match[1]+reverse.get(match[2],match[2])
    return re.sub(r'^(#{1,6} )([^\r\n]+)', restore, text, flags=re.M)


def reader_files():
    return sorted(p for p in VAULT.rglob('*.md')
                  if not any(part in {'编排记录', '编排维护', '.git'} for part in p.relative_to(VAULT).parts))


def optimize_tree(root):
    count=0
    for path in reader_files():
        if path.is_relative_to(root):
            before=path.read_bytes()
            after=rename_text(before.decode('utf-8'),path).encode('utf-8')
            if before!=after:
                path.write_bytes(after)
                count+=1
    return count
