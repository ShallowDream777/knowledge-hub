def translation_scale():
    return ('按本题答案所列的10个评分单元评分，每单元1分：意义单元的核心事实、逻辑与限制准确给1分；'
            '核心仍清楚但有一处次要遗漏或表达不完整给0.5分；主语／对象颠倒、否定／条件／比较译反或核心信息遗漏给0分。'
            '不同的准确中文措辞同样得分，不按与参考译文相似度评分。同一单元最多扣到0分，同一处错误不跨单元重复扣分。'
            '若单元单独评价中文表达，连贯自然给1分，能理解但局部生硬给0.5分，多处断裂影响理解给0分。\n\n')


def writing_scale(chapter):
    tasks = {
        14: '点明简化现代生活的主题1分；提出至少两项具体可实行的办法，每项1分；分别解释两项办法为什么有帮助，每项1分。',
        15: '说明提问对学习或工作的价值1分；解释怎样产生帮助1分；给至少一个具体例子1分；说明怎样负责任地提问1分；理由、例子与中心观点相互支持1分。',
        16: '明确回答机器翻译能否完全取代人工1分；实质讨论速度1分、准确性1分、不同语境或任务中的表现1分；用理由将这些讨论与立场连接1分。只列关键词不算实质讨论。',
    }
    return (f'| 维度 | 分值 | 本题怎样给分 |\n|---|---:|---|\n'
            f'| 任务完成 | 5 | {tasks[chapter]} |\n'
            '| 组织与论证 | 4 | 点题、每段有明确推进、句间连接清楚、收束回应主题，各1分；可用不同合理结构，不要求复刻范文段数。 |\n'
            '| 语言准确 | 4 | 4：句子基本完整，几乎没有影响理解的错误；3：少量错误但主要关系清楚；2：同类错误反复，大意仍清楚；1：多处主谓、句子边界或逻辑错误妨碍理解；0：难以形成连贯意思。 |\n'
            '| 词汇与表达 | 2 | 2：用词搭配多数准确，能按内容作必要变化；1：重复或搭配欠妥但可理解；0：频繁误用妨碍意思。生僻词数量不单独加分。 |\n\n'
            '建议通过条件：不少于150词，总分至少10/15，且任务完成至少4/5、语言准确至少2/4。'
            '这是本资料的训练标准，不是官方阅卷细则。与范文观点、例子或措辞不同，只要满足题目并表达清楚，不因此扣分。\n\n')


def assessment(chapter, exams, items):
    scope = '独立验收范围：' + '、'.join(exams) + '。\n\n' if exams else ''
    if chapter == 1:
        return ('本章为起点诊断，14项分别记录首次答案和卡点，不用一个总正确率决定是否继续。'
                '把卡点标成词义、句子结构、范围逻辑、对话衔接、补全或输出；记录后按顺序进入第02章。\n\n'
                '诊断中不会的内容可以先留空。之后学到对应章节时再回来解释原题，区分“现在会了”与“当时本来就会”。\n\n')
    if chapter in OPEN_POINTS:
        text = scope + '本组5题，每题2分，共10分。每题下列两个要点各1分；准确的等义表述均可。核心关系译反或结构未成立，对应要点不给分，不能只因措辞不同扣分。题干只要求改写或翻译时，以写出的句子是否表达要点评分，不额外要求语法术语说明。\n\n'
        text += '| 题号 | 要点一（1分） | 要点二（1分） |\n|---|---|---|\n'
        text += ''.join(f'| {q} | {a} | {b} |\n' for q,a,b in OPEN_POINTS[chapter])
        repair = {
            2: '给丢分句重新画出主干与括号边界，再解释修饰对象；指代有歧义时列出候选及各自依据。',
            3: '先标限定谓语，再给非谓语找到修饰对象／承接结构，最后重译；不要靠词尾或句中是否出现人来判断。',
            4: '逐项标出数量、对象、否定或情态被改在哪里，重写成不丢限制的句子。',
        }
        return text + f'\n建议至少8/10，并在不看答案时说明自己给出的关系。未得分的要点须修正：{repair[chapter]}\n\n'
    if chapter == 5:
        return (scope + '本组是一段四空访谈，每空1分，共4分。建议首次至少3/4；得分空还要能指出前面的提问目的或后面的答语证据。仅靠剩余选项凑出的空先标“不稳”。\n\n'
                '错空或不稳空：给选项写一个动作标签（问动机、问经历、问处理办法、问未来计划），再从头回读整段。修正后合上答案，重新解释四空怎样衔接；不能只背字母。\n\n')
    if chapter == 6:
        return (scope + '混合10题，答对每题1分，建议首次至少8/10。前五题核对本句替换意义，后五题核对填空的结构、搭配和上下文。\n\n'
                '卷面得分之外，另标能否说明本句依据：猜对而解释不出的题标“不稳”，不抹去实际答对记录。错题重新代入候选，写明它改了动作、程度、因果、条件还是词性，并选一个最接近的错误项说明区别。达到分数后，仍须对错题和不稳题完成解释再继续。\n\n')
    if chapter in [7,8,9,10]:
        focuses = {
            7: '为五题各标出原文证据，核对问的是最初目的、主要故障、住户要求、报告结论还是复查目的。',
            8: '分清工具功能与教师判断、例子内容与举例目的；推断时说明证据如何支持结论，而非凭选项语气。',
            9: '主旨和标题须覆盖全篇；buffer要代回原句；This须写出具体回指事件。',
            10: '给四条评论各写一句立场；区分支持目标、要求例外、接受联系渠道与质疑评价周期，组合概括须逐条成立。',
        }
        return (scope + '本组5题，答对每题1分，建议首次至少4/5。卷面得分之外，另记能否指出原文依据；只凭“这项比较温和”猜对的，先标“不稳”，不抹去实际答对记录。达到分数后仍须完成下述证据解释，再继续学习。\n\n'
                + focuses[chapter] + '\n\n'
                '对错题和不稳题，分别说明正确项的证据以及自己原选项改动的时间、对象、范围或论述作用。修正后遮住解析重述；不要求逐字背参考答案。\n\n')
    if chapter == 11:
        return (scope + '独立完成第三篇10空，每空1分，建议首次至少8/10。把答案全部放回文章后，能说出文章从线上展示转向资料核实与持续维护的过程。\n\n'
                '错空先标主要原因：结构、搭配、词义或篇章关系。再写出空白两侧的决定性内容，并比较自己选项与正确项；只写“语感不好”不能指导重做。隔天遮住答案重填错空并读完整段。\n\n')
    if chapter == 12:
        first = [q['编号'] for q in items if q['独立验收'] and q['题目'].startswith('第一轮')]
        second = [q['编号'] for q in items if q['独立验收'] and q['题目'].startswith('第二轮')]
        return (scope + '第二套三篇全部完成后再展开答案。两轮分开记：\n\n'
                '- 组装短语：' + '、'.join(first) + '，10空，建议至少8/10。\n'
                '- 整组回填：' + '、'.join(second) + '，10空，建议至少8/10。\n\n'
                '第一轮错：把完整搭配读出，说明词性和词义。第二轮错：先查前面是否已有谓语、是否需要原形，再查上下文意思。多个短语结构都可接时，必须用语意继续区分。\n\n'
                '若第一轮错误连带造成第二轮错误，卷面仍各按实际空白计分，错因记录只记一次并注明连带影响；不要误以为自己有两个互不相关的知识缺口。\n\n')
    if chapter == 13:
        return (scope + '本章独立验收只有一段翻译，直接按意义单元评10分，不另算“题目正确率”。\n\n'
                + translation_scale() + '建议至少8/10，并在修改后保留可能性、比较、否定和不同用户条件。先修关系错误，再改中文表达；隔天只看英文重新翻译丢分句。\n\n')
    if chapter == 14:
        return scope + '本章独立验收是一篇“简化现代生活”作文，按下表评15分，不计算选择题式的正确率。\n\n' + writing_scale(14) + '未达到时，先补未完成的任务，再重写一个最薄弱的段落；语言同类错误反复时，逐句标出主语与谓语后修改。保留首次稿和修订稿，不用范文替换自己的原稿。\n\n'
    if chapter in [15,16]:
        return ('本卷分三部分记录，避免用总分掩盖某一种任务没有完成。\n\n'
                '| 部分 | 记录方式 | 本套自学建议 |\n|---|---|---|\n'
                '| 客观题 | 口语10、词汇10、阅读25、完形10、短文完成20，逐项各1分 | 首次独立至少60/75，另记各题型用时与不稳题 |\n'
                '| 翻译 | 按本题所列10个意义单元 | 至少8/10 |\n'
                '| 作文 | 按下方本题量表 | 至少10/15，任务至少4/5、语言至少2/4，且不少于150词 |\n\n'
                '试卷一100分钟、试卷二50分钟；超时补答、查词后答案和复测另列。得分门槛用于安排补练，不预测考试通过率。\n\n'
                '翻译评分：' + translation_scale() + '作文评分：\n\n' + writing_scale(chapter)
                + ('第16章机器翻译作文主题已在第14章题库示范，本次作文仅计复写；不要将其与第15章首次陌生作文混为同一测量。\n\n' if chapter == 16 else '')
                + '复盘时先选两类最集中的错误，逐题留下证据、原判断和修正理由。隔天遮住解析重做；同分但耗时或错误分布不同，应补练不同内容。\n\n')
    raise ValueError(chapter)
